    # ── Helpers ──────────────────────────────────────────────
    @staticmethod
    def _slugify(text):
        """Simple slugify for region/city names."""
        import re
        slug = text.lower().strip()
        slug = re.sub(r'[^\w\s-]', '', slug)
        slug = re.sub(r'[\s_]+', '-', slug)
        slug = re.sub(r'-+', '-', slug)
        return slug.strip('-')

    @staticmethod
    def _img(seed_text, w=1200):
        """Generate a deterministic Unsplash source URL for a given text seed."""
        import re
        clean = re.sub(r'[^a-zA-Z0-9]', '', seed_text).lower()
        # Use a set of known-good Unsplash photo IDs cycling through for variety
        # but deterministic based on the text hash
        photo_ids = [
            '1513622470522-26c3c8a854bc',
            '1597212720156-3a2c0c4b8e36',
            '1508009603885-50cf7c579365',
            '1573152958734-1922c188fba3',
            '1597212618440-406323764935',
            '1559827260-dc66d52bef19',
            '1589909202802-8f4aadce1849',
            '1572252009286-268acec5ca0a',
            '1580983688229-996cd9a3c6e0',
            '1518738545787-4a3a3a3a3a3b',
            '1599887515723-39698b8c2a63',
            '1539067638422-76c3c8d4a3e3',
            '1516550893923-42d28e5677af',
            '1599661046289-e31897846e41',
            '1599227390096-cd0aeb893e3b',
        ]
        h = int(hashlib.md5(clean.encode()).hexdigest(), 16)
        pid = photo_ids[h % len(photo_ids)]
        return f'https://images.unsplash.com/photo-{pid}?w={w}&q=80'

    @staticmethod
    def _region_slug(country_slug, region_name):
        """Generate a unique region slug incorporating country prefix if needed."""
        import re
        base = Command._slugify(region_name)
        return f'{country_slug}-{base}' if base else country_slug

    @staticmethod
    def _city_slug(region_s, city_name):
        """Generate a unique city slug."""
        return Command._slugify(city_name)

