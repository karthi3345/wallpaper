    @transaction.atomic
    def handle(self, *args, **options):
        created = {'countries': 0, 'regions': 0, 'cities': 0}

        # Get sort_order offset: start after existing countries
        try:
            max_sort = Country.objects.order_by('-sort_order').first()
            start_sort = (max_sort.sort_order + 1) if max_sort else 0
        except Exception:
            start_sort = 0

        # Collect ALL slugs to ensure uniqueness
        existing_country_slugs = set(Country.objects.values_list('slug', flat=True))
        existing_region_slugs = set(Region.objects.values_list('slug', flat=True))
        existing_city_slugs = set(City.objects.values_list('slug', flat=True))

        for idx, (name, slug, description, regions_data) in enumerate(self.ADDITIONAL_COUNTRIES):
            if slug in existing_country_slugs:
                continue

            country_img = self._img(name, 1200)
            country = Country.objects.create(
                name=name,
                slug=slug,
                image=country_img,
                description=description,
                sort_order=start_sort + idx,
                is_active=True,
            )
            existing_country_slugs.add(slug)
            created['countries'] += 1

            for ridx, (region_name, city_names) in enumerate(regions_data):
                rslug = f'{slug}-{self._slugify(region_name)}'
                # Ensure unique region slug
                base_rslug = rslug
                counter = 1
                while rslug in existing_region_slugs:
                    rslug = f'{base_rslug}-{counter}'
                    counter += 1
                existing_region_slugs.add(rslug)

                region = Region.objects.create(
                    country=country,
                    name=region_name,
                    slug=rslug,
                    image=self._img(f'{name} {region_name}', 900),
                    description=f'Region of {name}.',
                    sort_order=ridx,
                    is_active=True,
                )
                created['regions'] += 1

                for cidx, city_name in enumerate(city_names):
                    cslug = self._slugify(city_name)
                    base_cslug = cslug
                    counter = 1
                    while cslug in existing_city_slugs:
                        cslug = f'{base_cslug}-{counter}'
                        counter += 1
                    existing_city_slugs.add(cslug)

                    City.objects.create(
                        region=region,
                        name=city_name,
                        slug=cslug,
                        image=self._img(f'{name} {city_name}', 900),
                        description=f'{city_name}, {region_name}, {name}.',
                        sort_order=cidx,
                        is_active=True,
                        featured=(cidx == 0),  # first city featured
                    )
                    created['cities'] += 1

        # ── Re-associate products with all cities ──────────
        all_products = list(Product.objects.all())
        all_cities = list(City.objects.all())

        if all_products and all_cities:
            import random
            random.seed(42)
            for product in all_products:
                num_cities = random.randint(1, min(3, len(all_cities)))
                chosen = random.sample(all_cities, num_cities)
                product.cities.set(chosen)

        self.stdout.write(
            self.style.SUCCESS(
                f'Seeded {created["countries"]} countries, '
                f'{created["regions"]} regions, '
                f'{created["cities"]} cities. '
                f'Re-associated {len(all_products)} products with cities.'
            )
        )
